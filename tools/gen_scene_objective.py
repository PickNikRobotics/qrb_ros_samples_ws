"""Write a planning-scene Objective from a compiled MuJoCo scene, so the planning scene matches the simulation.

Every collision geom of the selected static bodies, or of the selected world-body geoms, becomes a planning-scene box
or cylinder at its compiled world pose. Moving objects are left out: they are what the robot acts on.

Run inside a container with the mujoco Python package:
  # rml63_sim pick cell (static bodies)
  python3 gen_scene_objective.py <scene.xml> --name "QRB Load Scene" --bodies table1 table2 cardboard_box
  # qrb_amr_sim warehouse (world geoms from warehouse.xml, by class)
  python3 gen_scene_objective.py <scene.xml> --name "QRB AMR Load Scene" --world-class warehouse
"""

import argparse

import mujoco
import numpy as np

HEADER = """<?xml version="1.0" encoding="UTF-8" ?>
<!-- Generated by tools/gen_scene_objective.py from the compiled scene.xml. Adds the static world to the planning
     scene so the 3D Visualizer shows it and planning avoids it. Regenerate after changing scene.xml. -->
<root BTCPP_format="4" main_tree_to_execute="{name}">
  <BehaviorTree ID="{name}" _description="{description}">
    <Control ID="Sequence" name="LoadScene">"""
FOOTER = """    </Control>
  </BehaviorTree>
  <TreeNodesModel>
    <SubTree ID="{name}">
      <MetadataFields>
        <Metadata subcategory="QRB Samples" />
        <Metadata runnable="true" />
      </MetadataFields>
    </SubTree>
  </TreeNodesModel>
</root>"""


def pose_action(position, quat_wxyz, frame):
    w, x, y, z = quat_wxyz
    px, py, pz = position
    return (
        f'      <Action ID="CreatePoseStamped" reference_frame="{frame}" position_xyz="{px:.4f};{py:.4f};{pz:.4f}"'
        f' orientation_xyzw="{x:.6f};{y:.6f};{z:.6f};{w:.6f}" pose_stamped="{{pose}}" />'
    )


def object_actions(m, d, g, object_id, frame):
    quat = np.zeros(4)
    mujoco.mju_mat2Quat(quat, d.geom_xmat[g])
    size = m.geom_size[g]
    lines = [pose_action(d.geom_xpos[g], quat, frame)]
    if m.geom_type[g] == mujoco.mjtGeom.mjGEOM_BOX:
        sx, sy, sz = (2 * v for v in size)
        lines.append(
            f'      <Action ID="AddCollisionBox" object_id="{object_id}"'
            f' dimensions="{sx:.4f};{sy:.4f};{sz:.4f}" pose="{{pose}}" overwrite="true" />'
        )
    elif m.geom_type[g] == mujoco.mjtGeom.mjGEOM_CYLINDER:
        lines.append(
            f'      <Action ID="AddCollisionCylinder" object_id="{object_id}"'
            f' radius="{size[0]:.4f}" height="{2 * size[1]:.4f}" pose="{{pose}}" overwrite="true" />'
        )
    else:
        raise SystemExit(f"geom {object_id}: unsupported type {m.geom_type[g]}")
    return lines


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("scene")
    parser.add_argument("--name", required=True, help="Objective ID")
    parser.add_argument("--description", default="Add the static world to the planning scene.")
    parser.add_argument("--frame", default="world", help="planning frame the poses are expressed in")
    parser.add_argument("--bodies", nargs="*", default=[], help="static bodies whose collision geoms are added")
    parser.add_argument("--world-class", help="add world-body geoms defined with this MJCF default class")
    args = parser.parse_args()

    m = mujoco.MjModel.from_xml_path(args.scene)
    d = mujoco.MjData(m)
    mujoco.mj_resetDataKeyframe(m, d, m.key("default").id)
    mujoco.mj_forward(m, d)
    print(HEADER.format(name=args.name, description=args.description))
    for body in args.bodies:
        body_id = m.body(body).id
        index = 0
        for g in range(m.ngeom):
            if m.geom_bodyid[g] == body_id and m.geom_contype[g] != 0:
                index += 1
                print("\n".join(object_actions(m, d, g, f"{body}_{index}", args.frame)))
    if args.world_class:
        # MJCF default classes are not kept by name in mjModel, so match the geom names the generator emitted.
        for g in range(m.ngeom):
            name = m.geom(g).name
            if m.geom_bodyid[g] == 0 and m.geom_contype[g] != 0 and name and name != "floor":
                print("\n".join(object_actions(m, d, g, name, args.frame)))
    print(FOOTER.format(name=args.name))


if __name__ == "__main__":
    main()
