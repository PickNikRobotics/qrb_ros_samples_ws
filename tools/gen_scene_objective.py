"""Write objectives/qrb_load_scene.xml from the compiled MuJoCo scene, so the planning scene matches the simulation.

Every collision geom of the static furniture bodies (tables and cardboard box) becomes a planning-scene box or
cylinder at its compiled world pose. The cans are left out: they move and are grasped.
Run inside a container with the mujoco Python package:
  python3 gen_scene_objective.py <scene.xml> > <rml63_sim>/objectives/qrb_load_scene.xml
"""

import sys

import mujoco
import numpy as np

FURNITURE = ["table1", "table2", "cardboard_box"]

HEADER = """<?xml version="1.0" encoding="UTF-8" ?>
<!-- Generated by tools/gen_scene_objective.py from the compiled scene.xml. Adds the pick cell's static furniture to
     the planning scene so the 3D Visualizer shows it and planning avoids it. The cans stay out: they move and are
     grasped. Regenerate after changing scene.xml. -->
<root BTCPP_format="4" main_tree_to_execute="QRB Load Scene">
  <BehaviorTree ID="QRB Load Scene" _description="Add the QRB pick cell's tables and cardboard box to the planning scene.">
    <Control ID="Sequence" name="LoadScene">"""
FOOTER = """    </Control>
  </BehaviorTree>
  <TreeNodesModel>
    <SubTree ID="QRB Load Scene">
      <MetadataFields>
        <Metadata subcategory="QRB Samples" />
        <Metadata runnable="true" />
      </MetadataFields>
    </SubTree>
  </TreeNodesModel>
</root>"""


def pose_action(position, quat_wxyz):
    w, x, y, z = quat_wxyz
    px, py, pz = position
    return (
        f'      <Action ID="CreatePoseStamped" reference_frame="world" position_xyz="{px:.4f};{py:.4f};{pz:.4f}"'
        f' orientation_xyzw="{x:.6f};{y:.6f};{z:.6f};{w:.6f}" pose_stamped="{{pose}}" />'
    )


def main(scene):
    m = mujoco.MjModel.from_xml_path(scene)
    d = mujoco.MjData(m)
    mujoco.mj_resetDataKeyframe(m, d, m.key("default").id)
    mujoco.mj_forward(m, d)
    print(HEADER)
    for body in FURNITURE:
        body_id = m.body(body).id
        index = 0
        for g in range(m.ngeom):
            if m.geom_bodyid[g] != body_id or m.geom_contype[g] == 0:
                continue
            index += 1
            quat = np.zeros(4)
            mujoco.mju_mat2Quat(quat, d.geom_xmat[g])
            object_id = f"{body}_{index}"
            size = m.geom_size[g]
            print(pose_action(d.geom_xpos[g], quat))
            if m.geom_type[g] == mujoco.mjtGeom.mjGEOM_BOX:
                sx, sy, sz = (2 * v for v in size)
                print(
                    f'      <Action ID="AddCollisionBox" object_id="{object_id}"'
                    f' dimensions="{sx:.4f};{sy:.4f};{sz:.4f}" pose="{{pose}}" overwrite="true" />'
                )
            elif m.geom_type[g] == mujoco.mjtGeom.mjGEOM_CYLINDER:
                print(
                    f'      <Action ID="AddCollisionCylinder" object_id="{object_id}"'
                    f' radius="{size[0]:.4f}" height="{2 * size[1]:.4f}" pose="{{pose}}" overwrite="true" />'
                )
            else:
                raise SystemExit(f"{body} geom {g}: unsupported type {m.geom_type[g]}")
    print(FOOTER)


if __name__ == "__main__":
    main(sys.argv[1])
